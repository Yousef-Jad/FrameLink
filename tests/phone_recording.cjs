const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let now = 0;
let intervalCallback = null;
const elements = new Map(['record-btn', 'record-timer', 'record-state', 'record-mode', 'record-policy', 'record-error'].map(id => [id, {textContent: '', disabled: true, setAttribute() {}, addEventListener() {}, classList: {toggle() {}}}]));
const sandbox = {window: {}, document: {getElementById: id => elements.get(id)}, performance: {now: () => now}, setInterval: callback => { intervalCallback = callback; return 1; }, clearInterval: () => {}, crypto: require('node:crypto').webcrypto};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('src/framelink/web/recording.js', 'utf8') + '\nglobalThis.Controls = RecordingControls;', sandbox);
const controls = new sandbox.Controls();
sandbox.window.framelinkRecording = controls;
const sent = [];
const channel = {readyState: 'open', send: text => sent.push(JSON.parse(text))};
const snapshot = (state, revision, elapsed = 0) => ({state, revision, elapsed, mode: 'both', disconnect_policy: 'hide', can_start: ['Ready', 'Completed', 'Error'].includes(state), can_stop: ['Preparing', 'Recording', 'Paused'].includes(state), error: ''});
controls.setChannel(channel);
assert.equal(elements.get('record-btn').disabled, true, 'No control until desktop confirms state');
controls.receive({recorder: snapshot('Ready', 1)});
assert.equal(elements.get('record-btn').disabled, false);
controls.command();
controls.command();
assert.equal(sent.length, 1, 'Duplicate taps submit one command');
assert.equal(sent[0].action, 'start');
assert.equal(sent[0].revision, 1);
assert.notEqual(elements.get('record-btn').textContent, 'Stop', 'Sending is not recording confirmation');
controls.receive({type: 'recording-result', id: sent[0].id, ok: true, recorder: snapshot('Preparing', 2)});
assert.notEqual(elements.get('record-state').textContent, 'Recording');
controls.receive({recorder: snapshot('Recording', 3, 65)});
assert.equal(elements.get('record-btn').textContent, 'Stop');
assert.equal(elements.get('record-timer').textContent, '00:01:05');
now = 1100;
controls.render();
assert.equal(elements.get('record-timer').textContent, '00:01:06');
controls.receive({recorder: snapshot('Recording', 3, 66)});
now = 2100;
controls.render();
assert.equal(elements.get('record-timer').textContent, '00:01:07', 'Heartbeats rebase rather than double-count elapsed time');
controls.receive({recorder: snapshot('Paused', 4, 66)});
now = 2200;
controls.render();
assert.equal(elements.get('record-timer').textContent, '00:01:06');
controls.command();
assert.equal(sent[1].action, 'stop');
controls.receive({type: 'recording-result', id: sent[1].id, ok: true, recorder: snapshot('Stopping', 5, 66)});
assert.equal(elements.get('record-btn').disabled, true);
controls.receive({recorder: snapshot('Completed', 6, 66)});
assert.equal(elements.get('record-btn').textContent, 'Record');
controls.receive({recorder: snapshot('Recording', 3, 2)});
assert.equal(elements.get('record-btn').textContent, 'Record', 'Old responses cannot resurrect recording');
controls.command();
controls.receive({type: 'recording-result', id: sent[2].id, ok: false, error: 'Start screen preview before recording', recorder: snapshot('Ready', 7)});
assert.match(elements.get('record-error').textContent, /preview/);
controls.receive({recorder: snapshot('Ready', 7)});
assert.match(elements.get('record-error').textContent, /preview/, 'Heartbeat must not hide command errors');
controls.command();
now += 7000;
intervalCallback();
assert.equal(elements.get('record-btn').disabled, true);
assert.match(elements.get('record-state').textContent, /unknown|unavailable/i);
assert.match(elements.get('record-error').textContent, /confirm/i);
controls.setChannel(null);
assert.equal(elements.get('record-btn').disabled, true);
controls.setChannel(channel);
assert.equal(elements.get('record-btn').disabled, true, 'Reconnect requires a fresh snapshot');
controls.receive({recorder: snapshot('Recording', 8, 100)});
assert.equal(elements.get('record-btn').textContent, 'Stop');
channel.send = () => { throw new Error('closed'); };
controls.command();
assert.equal(elements.get('record-btn').disabled, true);
assert.match(elements.get('record-error').textContent, /confirm|connection/i);
console.log('Phone Record/Stop acknowledgement, timer, conflict and disconnect checks passed');
